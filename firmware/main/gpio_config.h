#pragma once

/* ------------------------------------------------------------------ */
/*  STEP / DIR per axis                                                 */
/* ------------------------------------------------------------------ */
#define GPIO_STEP0   4
#define GPIO_STEP1   6
#define GPIO_STEP2   8
#define GPIO_STEP3  10

#define GPIO_DIR0    5
#define GPIO_DIR1    7
#define GPIO_DIR2    9
#define GPIO_DIR3   11

/* ------------------------------------------------------------------ */
/*  DRV8825 共通制御 (全軸共通)                                          */
/* ------------------------------------------------------------------ */
#define GPIO_DRV_EN      12   /* アクティブ Low  */
#define GPIO_DRV_RESET   13   /* アクティブ Low  */
#define GPIO_DRV_SLEEP   14   /* アクティブ High */

/* ------------------------------------------------------------------ */
/*  マイクロステップ (全軸共通)                                           */
/*  NOTE: GPIO22/23/24 は ESP32-S3 内部 SPI Flash 専用のため使用不可。    */
/*  回路図変更により GPIO41/42/45 に再アサイン済み。                       */
/*  GPIO45 はストラップピンだが起動後は通常 GPIO として使用可能。           */
/* ------------------------------------------------------------------ */
#define GPIO_M0  41
#define GPIO_M1  42
#define GPIO_M2  45

/* ------------------------------------------------------------------ */
/*  エンコーダ A/B 相                                                   */
/* ------------------------------------------------------------------ */
#define GPIO_ENC0_A  15
#define GPIO_ENC0_B  16
#define GPIO_ENC1_A  17
#define GPIO_ENC1_B  18
#define GPIO_ENC2_A  21
#define GPIO_ENC2_B  35
#define GPIO_ENC3_A  36
#define GPIO_ENC3_B  37

/* ------------------------------------------------------------------ */
/*  ADC チャンネル                                                      */
/* ------------------------------------------------------------------ */
#define GPIO_ADC0   1
#define GPIO_ADC1   2
#define GPIO_ADC2   3
#define GPIO_ADC3  40

/* ------------------------------------------------------------------ */
/*  USB D- / D+                                                        */
/* ------------------------------------------------------------------ */
#define GPIO_USB_DM  19
#define GPIO_USB_DP  20

/* ------------------------------------------------------------------ */
/*  I2C 拡張                                                           */
/* ------------------------------------------------------------------ */
#define GPIO_I2C_SDA  38
#define GPIO_I2C_SCL  39

/* ------------------------------------------------------------------ */
/*  軸数                                                               */
/* ------------------------------------------------------------------ */
#define NUM_AXES  4

/* GPIO 配列 (軸番号でインデックス) */
#define STEP_GPIOS  { GPIO_STEP0, GPIO_STEP1, GPIO_STEP2, GPIO_STEP3 }
#define DIR_GPIOS   { GPIO_DIR0,  GPIO_DIR1,  GPIO_DIR2,  GPIO_DIR3  }
